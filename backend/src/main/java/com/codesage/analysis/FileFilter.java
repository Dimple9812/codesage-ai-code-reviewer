package com.codesage.analysis;

import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.Set;
import java.util.regex.Pattern;

/** Decides which repository files are worth reviewing; excludes generated, vendored and build output. */
public final class FileFilter {

    private static final Set<String> EXCLUDED_DIRS = Set.of(
            "node_modules", "vendor", "vendors", "third_party", "third-party", "dist", "build", "target", "out",
            ".git", ".idea", ".vscode", "__pycache__", ".venv", "venv", "env", ".tox", "coverage", ".next",
            ".nuxt", ".gradle", "bin", "obj", "generated", "gen", ".mvn", "bower_components", "site-packages",
            ".terraform", "migrations-generated");

    private static final List<Pattern> EXCLUDED_FILES = List.of(
            Pattern.compile(".*\\.min\\.(js|css)$"),
            Pattern.compile(".*\\.map$"),
            Pattern.compile(".*(package-lock\\.json|yarn\\.lock|pnpm-lock\\.yaml|composer\\.lock|poetry\\.lock|go\\.sum|cargo\\.lock)$"),
            Pattern.compile(".*\\.pb\\.go$"),
            Pattern.compile(".*_pb2(_grpc)?\\.py$"),
            Pattern.compile(".*\\.generated\\.[a-z]+$"),
            Pattern.compile(".*\\.d\\.ts$"),
            Pattern.compile(".*(^|/)tsconfig\\..*\\.json$"));

    private static final Pattern GENERATED_MARKER = Pattern.compile(
            "(@generated|Code generated .* DO NOT EDIT|This file was automatically generated|<auto-generated)",
            Pattern.CASE_INSENSITIVE);

    private FileFilter() {
    }

    public static Optional<String> exclusionReason(String path) {
        String lower = path.toLowerCase(Locale.ROOT);
        for (String segment : lower.split("/")) {
            if (EXCLUDED_DIRS.contains(segment)) {
                return Optional.of("Excluded directory: " + segment);
            }
        }
        for (Pattern p : EXCLUDED_FILES) {
            if (p.matcher(lower).matches()) {
                return Optional.of("Generated, vendored or lock file");
            }
        }
        if (Language.detect(path).isEmpty()) {
            return Optional.of("Unsupported file type");
        }
        return Optional.empty();
    }

    public static boolean looksGenerated(String content) {
        String head = content.length() > 1500 ? content.substring(0, 1500) : content;
        return GENERATED_MARKER.matcher(head).find();
    }

    public static boolean looksBinary(String content) {
        int limit = Math.min(content.length(), 4000);
        for (int i = 0; i < limit; i++) {
            if (content.charAt(i) == '\u0000') {
                return true;
            }
        }
        return false;
    }

    /** Lower value = reviewed first: application source before tests before configuration. */
    public static int priority(String path, Language language) {
        String lower = path.toLowerCase(Locale.ROOT);
        boolean test = lower.contains("/test/") || lower.contains("/tests/") || lower.contains("__tests__")
                || lower.matches(".*(\\.test|\\.spec|_test)\\.[a-z]+$") || lower.matches(".*/test_[^/]+\\.py$");
        return switch (language) {
            case JSON, YAML, CONFIG -> 3;
            case SQL -> 2;
            default -> test ? 2 : 1;
        };
    }
}

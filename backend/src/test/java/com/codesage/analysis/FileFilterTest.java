package com.codesage.analysis;

import static org.assertj.core.api.Assertions.assertThat;

import org.junit.jupiter.api.Test;

class FileFilterTest {

    @Test
    void excludesVendoredGeneratedAndBuildOutput() {
        assertThat(FileFilter.exclusionReason("node_modules/react/index.js")).isPresent();
        assertThat(FileFilter.exclusionReason("app/target/classes/A.java")).isPresent();
        assertThat(FileFilter.exclusionReason("web/dist/app.min.js")).isPresent();
        assertThat(FileFilter.exclusionReason("package-lock.json")).isPresent();
        assertThat(FileFilter.exclusionReason("api/service.pb.go")).isPresent();
        assertThat(FileFilter.exclusionReason("logo.png")).isPresent();
    }

    @Test
    void keepsRegularSource() {
        assertThat(FileFilter.exclusionReason("src/main/java/com/x/UserService.java")).isEmpty();
        assertThat(FileFilter.exclusionReason("app/views.py")).isEmpty();
        assertThat(FileFilter.exclusionReason("Dockerfile")).isEmpty();
    }

    @Test
    void detectsGeneratedMarkersAndBinaryContent() {
        assertThat(FileFilter.looksGenerated("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x")).isTrue();
        assertThat(FileFilter.looksGenerated("package x\nfunc main() {}")).isFalse();
        assertThat(FileFilter.looksBinary("abc\u0000def")).isTrue();
    }

    @Test
    void detectsLanguages() {
        assertThat(Language.detect("a/b/C.java")).contains(Language.JAVA);
        assertThat(Language.detect("x.tsx")).contains(Language.TYPESCRIPT);
        assertThat(Language.detect("k8s/deploy.yaml")).contains(Language.YAML);
        assertThat(Language.detect("README.md")).isEmpty();
    }

    @Test
    void prioritisesSourceOverTestsAndConfig() {
        assertThat(FileFilter.priority("src/main/A.java", Language.JAVA))
                .isLessThan(FileFilter.priority("src/test/ATest.java", Language.JAVA));
        assertThat(FileFilter.priority("src/a.ts", Language.TYPESCRIPT))
                .isLessThan(FileFilter.priority("config.json", Language.JSON));
    }
}

import clsx from "clsx";
import { Bot, CheckCircle2, CircleDashed, Loader2, ShieldCheck, XCircle, Ban } from "lucide-react";

import type { FindingCategory, FindingSource, ReviewStatus, Severity, Verification } from "../api/types";
import { categoryLabel, severityLabel, statusLabel } from "../lib/format";

const SEV_CLASSES: Record<Severity, string> = {
  CRITICAL: "text-sev-critical border-sev-critical/50 bg-sev-critical/12",
  HIGH: "text-sev-high border-sev-high/50 bg-sev-high/12",
  MEDIUM: "text-sev-medium border-sev-medium/50 bg-sev-medium/10",
  LOW: "text-sev-low border-sev-low/50 bg-sev-low/10",
  INFO: "text-sev-info border-sev-info/40 bg-sev-info/10",
};

export const SEV_TEXT: Record<Severity, string> = {
  CRITICAL: "text-sev-critical",
  HIGH: "text-sev-high",
  MEDIUM: "text-sev-medium",
  LOW: "text-sev-low",
  INFO: "text-sev-info",
};

export const SEV_HEX: Record<Severity, string> = {
  CRITICAL: "#f27474",
  HIGH: "#f0a35e",
  MEDIUM: "#e7cf62",
  LOW: "#7fb6e8",
  INFO: "#9aa8b8",
};

export function SeverityBadge({ severity }: { severity: Severity }) {
  return (
    <span className={clsx("inline-flex items-center rounded border px-1.5 py-0.5 text-xs font-semibold", SEV_CLASSES[severity])}>
      {severityLabel(severity)}
    </span>
  );
}

export function CategoryTag({ category }: { category: FindingCategory }) {
  return <span className="rounded bg-raised px-1.5 py-0.5 text-xs text-muted">{categoryLabel(category)}</span>;
}

export function SourceBadge({ source, analyzer, verification }: { source: FindingSource; analyzer: string; verification: Verification }) {
  if (source === "AI") {
    return (
      <span
        className="inline-flex items-center gap-1 rounded bg-raised px-1.5 py-0.5 text-xs text-muted"
        title="Generated by the AI model. Not verified by executing code or tests."
      >
        <Bot className="size-3.5" aria-hidden /> AI · unverified
      </span>
    );
  }
  const name = analyzer === "pmd" ? "PMD" : analyzer === "semgrep" ? "Semgrep" : "CodeSage rules";
  return (
    <span
      className="inline-flex items-center gap-1 rounded bg-sage-deep/60 px-1.5 py-0.5 text-xs text-sage-strong"
      title={verification === "CONFIRMED_BY_TEST" ? "Confirmed by an executed test" : "Reported by a deterministic static analyzer"}
    >
      <ShieldCheck className="size-3.5" aria-hidden /> {name}
    </span>
  );
}

const STATUS_STYLE: Record<ReviewStatus, { cls: string; icon: typeof CheckCircle2 }> = {
  QUEUED: { cls: "text-muted", icon: CircleDashed },
  RUNNING: { cls: "text-pollen", icon: Loader2 },
  COMPLETED: { cls: "text-sage", icon: CheckCircle2 },
  FAILED: { cls: "text-sev-critical", icon: XCircle },
  CANCELLED: { cls: "text-faint", icon: Ban },
};

export function StatusPill({ status }: { status: ReviewStatus }) {
  const { cls, icon: Icon } = STATUS_STYLE[status];
  return (
    <span className={clsx("inline-flex items-center gap-1.5 text-sm", cls)}>
      <Icon className={clsx("size-4", status === "RUNNING" && "animate-spin")} aria-hidden />
      {statusLabel(status)}
    </span>
  );
}

/** Review score as a partial ring. Colour follows the same thresholds everywhere. */
export function ScoreDial({ score, size = 56 }: { score: number | null; size?: number }) {
  const r = (size - 8) / 2;
  const c = 2 * Math.PI * r;
  const value = score ?? 0;
  const color = score == null ? "var(--color-faint)" : value >= 85 ? "var(--color-sage)" : value >= 65 ? "var(--color-pollen)" : "var(--color-sev-critical)";
  return (
    <div className="relative inline-grid place-items-center" style={{ width: size, height: size }} aria-label={score == null ? "No score" : `Score ${score} of 100`} role="img">
      <svg width={size} height={size} className="-rotate-90">
        <circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke="var(--color-line)" strokeWidth="5" />
        <circle
          cx={size / 2}
          cy={size / 2}
          r={r}
          fill="none"
          stroke={color}
          strokeWidth="5"
          strokeLinecap="round"
          strokeDasharray={`${(value / 100) * c} ${c}`}
        />
      </svg>
      <span className={clsx("absolute font-bold tabular-nums", size < 48 ? "text-[11px]" : "text-sm")}>{score ?? "–"}</span>
    </div>
  );
}

export function SeverityBar({ counts }: { counts: { critical: number; high: number; medium: number; low: number; info: number } }) {
  const parts: [Severity, number][] = [
    ["CRITICAL", counts.critical],
    ["HIGH", counts.high],
    ["MEDIUM", counts.medium],
    ["LOW", counts.low],
    ["INFO", counts.info],
  ];
  const total = parts.reduce((s, [, n]) => s + n, 0);
  if (total === 0) return <span className="text-xs text-faint">No findings</span>;
  return (
    <div className="flex items-center gap-2" aria-label={parts.map(([s, n]) => `${n} ${s.toLowerCase()}`).join(", ")}>
      <div className="flex h-1.5 w-24 overflow-hidden rounded-full bg-line">
        {parts.map(([s, n]) => (n ? <div key={s} style={{ width: `${(n / total) * 100}%`, background: SEV_HEX[s] }} /> : null))}
      </div>
      <span className="text-xs tabular-nums text-muted">{total}</span>
    </div>
  );
}
